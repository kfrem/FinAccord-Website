// Get current language
function getCurrentLang() {
    return localStorage.getItem('finaccord_lang') || 'en';
}

// Set language and update all elements
function setLang(lang) {
    localStorage.setItem('finaccord_lang', lang);
    document.documentElement.setAttribute('data-lang', lang);
    document.documentElement.setAttribute('lang', lang);

    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update language toggle buttons
    document.querySelectorAll('.lang-toggle__btn').forEach(btn => {
        btn.classList.remove('lang-toggle__btn--active');
        if (btn.textContent.trim() === lang.toUpperCase()) {
            btn.classList.add('lang-toggle__btn--active');
        }
    });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
    const lang = getCurrentLang();
    if (lang !== 'en') {
        setLang(lang);
    }
});
